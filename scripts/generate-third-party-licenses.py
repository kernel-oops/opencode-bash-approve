#!/usr/bin/env python3
"""Generate the deterministic licence bundle for linked Linux/amd64 Go modules."""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
GO_DIR = ROOT / "hooks" / "bash-approve"
LEGAL_NAME = re.compile(
    r"(?:^|[._-])(?:LICEN[CS]E|COPYING|NOTICE|AUTHORS?|CONTRIBUTORS?|"
    r"PATENTS?|COPYRIGHT|LEGAL)(?:$|[._-])",
    re.IGNORECASE,
)


def decode_json_stream(data: str) -> list[dict[str, Any]]:
    decoder = json.JSONDecoder()
    objects: list[dict[str, Any]] = []
    offset = 0
    while offset < len(data):
        while offset < len(data) and data[offset].isspace():
            offset += 1
        if offset == len(data):
            break
        value, offset = decoder.raw_decode(data, offset)
        if not isinstance(value, dict):
            raise ValueError("go list returned a non-object JSON value")
        objects.append(value)
    return objects


def linked_modules() -> list[tuple[str, str, Path, str | None]]:
    env = os.environ.copy()
    env.update({"CGO_ENABLED": "0", "GOOS": "linux", "GOARCH": "amd64"})
    result = subprocess.run(
        ["go", "list", "-deps", "-json", "."],
        cwd=GO_DIR,
        env=env,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )
    modules: dict[tuple[str, str, str], tuple[str, str, Path, str | None]] = {}
    for package in decode_json_stream(result.stdout):
        module = package.get("Module")
        if not module or module.get("Main"):
            continue
        source = module.get("Replace") or module
        path = str(module["Path"])
        version = str(module.get("Version", ""))
        source_dir = Path(str(source["Dir"]))
        replacement = None
        if module.get("Replace"):
            replacement = f"{source.get('Path', '')} {source.get('Version', '')}".strip()
        key = (path, version, str(source_dir))
        modules[key] = (path, version, source_dir, replacement)
    return [modules[key] for key in sorted(modules)]


def legal_files(module_dir: Path) -> list[Path]:
    files = [
        path
        for path in module_dir.iterdir()
        if path.is_file() and LEGAL_NAME.search(path.name)
    ]
    return sorted(files, key=lambda path: path.name.encode("utf-8"))


def generate() -> str:
    modules = linked_modules()
    sections = [
        "THIRD-PARTY LICENCES AND NOTICES",
        "",
        "Target: linux/amd64 with CGO disabled",
        "Scope: every external Go module linked into approve-bash",
        "Generated by scripts/generate-third-party-licenses.py; do not edit manually.",
        f"Module count: {len(modules)}",
        "",
    ]
    for path, version, module_dir, replacement in modules:
        files = legal_files(module_dir)
        if not files:
            raise RuntimeError(f"linked module has no top-level licence or notice file: {path} {version}")
        sections.extend(
            [
                "=" * 79,
                f"Module: {path}",
                f"Version: {version or '(none)'}",
                f"Files: {', '.join(file.name for file in files)}",
            ]
        )
        if replacement:
            sections.append(f"Replacement: {replacement}")
        sections.append("")
        for legal_file in files:
            text = legal_file.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
            sections.extend(
                [
                    "-" * 79,
                    f"File: {legal_file.name}",
                    "-" * 79,
                    text,
                    "",
                ]
            )
    return "\n".join(sections).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output", type=Path)
    mode.add_argument("--check", type=Path)
    args = parser.parse_args()

    generated = generate()
    if args.output:
        args.output.write_text(generated, encoding="utf-8")
        return 0

    expected = args.check.read_text(encoding="utf-8")
    if expected == generated:
        return 0
    sys.stderr.writelines(
        difflib.unified_diff(
            expected.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(args.check),
            tofile="generated",
        )
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
